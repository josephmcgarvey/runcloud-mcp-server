<?php

namespace App\Mcp\Tools;

use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\Support\Str;
use Laravel\Mcp\Request;
use Laravel\Mcp\Response;
use Laravel\Mcp\Server\Attributes\Name;
use Laravel\Mcp\Server\Tools\Annotations\IsDestructive;

#[Name('runcloud-create-system-user')]
#[IsDestructive(false)]
class CreateSystemUserTool extends RunCloudTool
{
    protected const GENERATED_PASSWORD_LENGTH = 40;

    protected string $description = <<<'TEXT'
    Create a Linux system user on a RunCloud server. Web applications run as system users and live
    in their home directories, so this is how you isolate one client or project from another.

    The password is generated by this server and returned exactly once — do not invent one. It is
    the SSH and SFTP password for the account, so it grants shell access to the server.

    Leave sudoers false unless the user genuinely needs to run privileged commands. A sudo-capable
    account can do anything on the server, which defeats the isolation this user exists to provide.
    TEXT;

    public function schema(JsonSchema $schema): array
    {
        return [
            'serverId' => $schema->integer()
                ->description('The server to create the user on.')
                ->required(),
            'username' => $schema->string()
                ->description('The Linux username. Lowercase letters, digits, hyphens and underscores.')
                ->required(),
            'sudoers' => $schema->boolean()
                ->description('Grant sudo. Defaults to false. Only enable when the user must run privileged commands.'),
        ];
    }

    protected function run(Request $request): Response
    {
        $request->validate([
            'serverId' => 'required|integer|min:1',
            'username' => 'required|string|max:32|regex:/^[a-z_][a-z0-9_-]*$/',
            'sudoers' => 'sometimes|boolean',
        ]);

        $password = Str::password(self::GENERATED_PASSWORD_LENGTH, symbols: false);
        $sudoers = (bool) $request->get('sudoers', false);

        $user = $this->client->post("servers/{$request->get('serverId')}/users", [
            'username' => $request->get('username'),
            'password' => $password,
            'sudoers' => $sudoers,
        ]);

        return Response::json([
            'systemUser' => $user,
            'password' => $password,
            'notice' => 'This password grants SSH and SFTP access to the server. It was generated now '.
                'and is shown only once — give it to the user and tell them to store it securely.'.
                ($sudoers ? ' This account has sudo, so it can run any command on the server.' : ''),
        ]);
    }
}
