<?php

namespace App\Mcp\Tools;

use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\Support\Str;
use Laravel\Mcp\Request;
use Laravel\Mcp\Response;
use Laravel\Mcp\Server\Attributes\Name;
use Laravel\Mcp\Server\Tools\Annotations\IsDestructive;

#[Name('runcloud-create-wordpress')]
#[IsDestructive(false)]
class CreateWordPressWebAppTool extends RunCloudTool
{
    /**
     * Alphanumeric for the same reason as the database tools: these are pasted into wp-config.php
     * and .env files where symbols need escaping.
     */
    protected const GENERATED_PASSWORD_LENGTH = 40;

    protected string $description = <<<'TEXT'
    Create a WordPress web application on a RunCloud server, including its database and a fully
    installed WordPress site.

    Passwords are generated by this server. Do NOT invent the WordPress admin password or the
    database password — model-generated passwords have poor entropy. Both are returned exactly once
    and cannot be retrieved afterwards, so relay them to the user and tell them to store them in a
    password manager immediately.

    The database name, user, and prefix are generated by RunCloud unless supplied.

    Use runcloud-system-users first to choose the account the site runs under. Consider
    disableWpCron with a wpCronInterval, which replaces WordPress's request-triggered cron with a
    real server cron job and is generally better for a busy site.
    TEXT;

    public function schema(JsonSchema $schema): array
    {
        return [
            'serverId' => $schema->integer()
                ->description('The server to create the site on.')
                ->required(),
            'name' => $schema->string()
                ->description('The web application name. Becomes the directory name.')
                ->required(),
            'domainName' => $schema->string()
                ->description('The primary domain, without a scheme.')
                ->required(),
            'siteTitle' => $schema->string()
                ->description('The WordPress site title.')
                ->required(),
            'adminUsername' => $schema->string()
                ->description('The WordPress administrator username. Avoid "admin".')
                ->required(),
            'adminEmail' => $schema->string()
                ->description('The WordPress administrator email address.')
                ->required(),
            'user' => $schema->integer()
                ->description('System user id from runcloud-system-users. Defaults to the runcloud user.'),
            'phpVersion' => $schema->string()
                ->enum(['php74rc', 'php80rc', 'php81rc', 'php82rc', 'php83rc'])
                ->description('PHP version. Defaults to the server default.'),
            'stack' => $schema->string()
                ->enum(['hybrid', 'nativenginx', 'customnginx'])
                ->description('Web stack. Defaults to hybrid.'),
            'stackMode' => $schema->string()
                ->enum(['production', 'development'])
                ->description('Defaults to production.'),
            'disableWpCron' => $schema->boolean()
                ->description('Replace WP-Cron with a real server cron job. Recommended for busy sites.'),
            'wpCronInterval' => $schema->integer()
                ->description('Server cron interval in minutes, 1 to 60. Only meaningful with disableWpCron.'),
        ];
    }

    protected function run(Request $request): Response
    {
        $request->validate([
            'serverId' => 'required|integer|min:1',
            'name' => 'required|string|max:64',
            'domainName' => 'required|string|max:253',
            'siteTitle' => 'required|string|max:255',
            'adminUsername' => 'required|string|max:60',
            'adminEmail' => 'required|email',
            'user' => 'sometimes|integer|min:1',
            'phpVersion' => 'sometimes|string|in:php74rc,php80rc,php81rc,php82rc,php83rc',
            'stack' => 'sometimes|string|in:hybrid,nativenginx,customnginx',
            'stackMode' => 'sometimes|string|in:production,development',
            'disableWpCron' => 'sometimes|boolean',
            'wpCronInterval' => 'sometimes|integer|min:1|max:60',
        ]);

        $adminPassword = Str::password(self::GENERATED_PASSWORD_LENGTH, symbols: false);
        $databasePassword = Str::password(self::GENERATED_PASSWORD_LENGTH, symbols: false);

        $payload = [
            'name' => $request->get('name'),
            'domainName' => $request->get('domainName'),
            'siteTitle' => $request->get('siteTitle'),
            'adminUsername' => $request->get('adminUsername'),
            'adminEmail' => $request->get('adminEmail'),
            'password' => $adminPassword,
            'dbPassword' => $databasePassword,
        ];

        $optional = ['user', 'phpVersion', 'stack', 'stackMode', 'disableWpCron', 'wpCronInterval'];

        foreach ($optional as $key) {
            if (filled($request->get($key))) {
                $payload[$key] = $request->get($key);
            }
        }

        $webapp = $this->client->post("servers/{$request->get('serverId')}/webapps/wordpress", $payload);

        return Response::json([
            'webapp' => $webapp,
            'wordpressAdminUsername' => $request->get('adminUsername'),
            'wordpressAdminPassword' => $adminPassword,
            'databasePassword' => $databasePassword,
            'notice' => 'Both passwords were generated now and are shown only once. RunCloud cannot '.
                'return them again. Give them to the user and tell them to store them securely. The '.
                'site is not yet reachable over HTTPS — issue a certificate with runcloud-install-ssl.',
        ]);
    }
}
